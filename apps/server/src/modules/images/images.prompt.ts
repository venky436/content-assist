export function buildImagePrompt(input: {
	idea: string;
	caption?: string;
	modifier?: string;
}): string {
	const lines = [
		"Turn this creator idea into 3 scene prompts — struggle, decision, result — with short content-appropriate labels.",
		"",
		`Idea: "${input.idea.trim()}"`,
	];
	if (input.caption) {
		lines.push(`Caption: "${input.caption.trim()}"`);
	}
	if (input.modifier) {
		lines.push(`Modifier (applies to all 3 scenes): "${input.modifier.trim()}"`);
	}
	lines.push(
		"",
		"FIRST decide the SUBJECT TYPE (person / place / object / abstract) based on the idea.",
		"Then return the JSON exactly as specified.",
		"Each scene prompt MUST include SUBJECT + ACTION + ENVIRONMENT + WHY-CLUE + MOOD + LIGHTING + STYLE, 30–55 words.",
		"DO NOT force a human subject on travel / object / abstract ideas — let the subject BE the place, the thing, or the visual metaphor.",
		"DO NOT default to laptop / phone / desk unless the idea is literally about screens.",
		"Labels must be short, content-appropriate, and NEVER the words struggle / decision / result.",
	);
	return lines.join("\n");
}
