export function buildAnalyzeCorrectorPrompt(input: {
	content: string;
	previous: unknown;
	failures: string[];
}): string {
	return [
		"Your previous analysis of this content had specific failures.",
		"",
		"Content:",
		`"""${input.content.trim()}"""`,
		"",
		"Previous response:",
		JSON.stringify(input.previous, null, 2),
		"",
		"Failures to fix:",
		...input.failures.map((f) => `- ${f}`),
		"",
		"Return the FULL JSON response again, correcting ONLY the failures above. Keep everything else that was already working. Same output shape as before. Return ONLY valid JSON.",
	].join("\n");
}

export function buildAnalyzeTaskPrompt(content: string): string {
	const trimmed = content.trim();
	return [
		"Analyze this content:",
		"",
		`"""${trimmed}"""`,
		"",
		"Separate the hook (first line or strongest opener) from the caption (remaining lines).",
		"If only a caption is provided, treat its first sentence as the hook.",
		"Echo back the exact hook you detected as \"originalHook\".",
		"",
		"Return ONLY valid JSON (no markdown, no prose, no fences) with this exact shape:",
		"{",
		'  "score": <integer 0-100>,',
		'  "verdict": "Weak" | "Average" | "Strong" | "Very Strong",',
		'  "explanation": "1–2 sentences. Lead with what is WORKING, then name the ONE thing to sharpen. Max 35 words.",',
		'  "originalHook": "The exact hook you detected from the input, verbatim.",',
		'  "quickFix": "ONE sentence. The single most important change the creator should make right now. Max 20 words.",',
		'  "problems": ["EXACTLY 2–3 items. Each targets a DIFFERENT dimension (hook specificity / emotional trigger / CTA strength / clarity). If score >= 65, phrase as suggestions. If score < 60, phrase directly."],',
		'  "captionIssues": ["EXACTLY 2–3 items. Each targets a DIFFERENT dimension. Each MUST have WHY + WHAT."],',
		'  "betterHook": "<=8 words. Must improve curiosity, specificity, tension, or boldness vs. the original.",',
		'  "hookReason": "Max 18 words. Human voice. Explain which lever the rewrite pulls, referencing the topic.",',
		'  "improvedCaption": "Line1\\nLine2. Line1 = problem or insight, Line2 = CTA. <180 chars total.",',
		'  "captionReason": "Max 18 words. Name what changed and why.",',
		'  "insight": "Coach\'s take. Exactly 2-3 SHORT sentences separated by newlines. No paragraphs. Sharp, punchy, mentor voice. Max 50 words total.",',
		'  "priorityFix": "hook" | "caption",',
		'  "confidence": "low" | "medium" | "high"',
		"}",
		"",
		"Confidence rules: \"high\" when input is ≥10 words and has clear hook+caption structure; \"medium\" for partial content or ambiguous structure; \"low\" when input is short or ambiguous.",
	].join("\n");
}
